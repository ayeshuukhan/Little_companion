// emotionDetector.ts
//
// The ONE intelligent responsibility in this whole app: read the user's
// written text and decide whether it feels "happy" or "sad" (optionally
// "neutral"). Nothing here writes copy, gives advice, or continues a
// conversation — it only classifies.
//
// A local heuristic classifier ships as the default so the app works
// immediately with no backend or API key. Swap in `remoteClassifier`
// (see below) to call a real model from your own server instead —
// the rest of the app never needs to change, since both implement
// the same `classifyEmotion` signature.

export type Emotion = "happy" | "sad" | "neutral";

export interface EmotionClassifier {
  classify(text: string): Promise<Emotion>;
}


