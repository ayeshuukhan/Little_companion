/**
 * Default, dependency-free classifier. Good enough for an MVP demo and
 * keeps the whole app runnable offline. It scores keyword hits and a
 * few punctuation/emoji cues, then picks whichever side wins.
 */
export const localHeuristicClassifier: EmotionClassifier = {
  async classify(text: string): Promise<Emotion> {
    const t = text.toLowerCase();

    let happyScore = 0;
    let sadScore = 0;

    for (const word of HAPPY_WORDS) if (t.includes(word)) happyScore++;
    for (const word of SAD_WORDS) if (t.includes(word)) sadScore++;

    // light punctuation/emoji cues
    if (/!{2,}/.test(text)) happyScore += 1;
    if (/[😀😃😄😁😆🎉🥳💖✨]/u.test(text)) happyScore += 2;
    if (/[😢😭💔😞😔😩]/u.test(text)) sadScore += 2;

    if (happyScore === 0 && sadScore === 0) return "neutral";
    if (happyScore === sadScore) return "neutral";
    return happyScore > sadScore ? "happy" : "sad";
  },
};

/**
 * Optional: swap this in to call a real model instead of the heuristic.
 * Point it at your OWN backend endpoint — never call a model API directly
 * from the browser with an embedded key. Your endpoint should accept
 * { text } and return { emotion: "happy" | "sad" | "neutral" }.
 *
 * Example server-side prompt for the model:
 *   "Classify the emotional tone of this message as exactly one word:
 *    happy, sad, or neutral. Respond with only that word."
 */
export function createRemoteClassifier(endpoint: string): EmotionClassifier {
  return {
    async classify(text: string): Promise<Emotion> {
      const res = await fetch(endpoint, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ text }),
      });

      if (!res.ok) throw new Error(`Classifier request failed: ${res.status}`);

      const data = (await res.json()) as { emotion: Emotion };
      if (!["happy", "sad", "neutral"].includes(data.emotion)) {
        throw new Error(`Unexpected classifier response: ${data.emotion}`);
      }
      return data.emotion;
    },
  };
}

/**
 * Tries a primary classifier first, and silently falls back to a backup
 * if it throws (server not running, no API key configured, network
 * error, etc.) — so the app is never dead in the water waiting on a
 * backend that isn't there.
 */
function withFallback(primary: EmotionClassifier, fallback: EmotionClassifier): EmotionClassifier {
  return {
    async classify(text: string): Promise<Emotion> {
      try {
        return await primary.classify(text);
      } catch (err) {
        console.warn("Remote classifier unavailable, using local fallback:", err);
        return fallback.classify(text);
      }
    },
  };
}

// The classifier the app actually uses. This calls the local server in
// server/index.js (see README for setup), which asks a real model —
// genuinely understanding tone, sarcasm, and mixed/long messages instead
// of just keyword-matching. If that server isn't running or has no API
// key configured, it falls back to the offline heuristic automatically.
export const activeClassifier: EmotionClassifier = withFallback(
  createRemoteClassifier("/api/classify-emotion"),
  localHeuristicClassifier
);

export async function detectEmotion(text: string): Promise<Emotion> {
  const trimmed = text.trim();
  if (!trimmed) throw new Error("Cannot classify empty text");
  return activeClassifier.classify(trimmed);
}
